const EN = { ...EN_EXTRA };

// guarda o texto inglês original que está no index.html
document.querySelectorAll('[data-i18n]').forEach((el) => { EN[el.dataset.i18n] = el.textContent; });
document.querySelectorAll('[data-i18n-html]').forEach((el) => { EN[el.dataset.i18nHtml] = el.innerHTML; });
document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { EN[el.dataset.i18nPlaceholder] = el.placeholder; });

let currentLang = 'en';

function t(key) {
  const dict = currentLang === 'pt' ? PT : EN;
  return dict[key] ?? EN[key] ?? key;
}

function setLanguage(lang) {
  currentLang = lang === 'pt' ? 'pt' : 'en';
  document.documentElement.lang = currentLang;

  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });

  document.querySelectorAll('[data-lang]').forEach((btn) => {
    btn.classList.toggle('is-active', btn.dataset.lang === currentLang);
    btn.setAttribute('aria-pressed', btn.dataset.lang === currentLang);
  });

  try { localStorage.setItem('mbv-lang', currentLang); } catch (e) {}

  // avisa o resto do site (ex: efeito de escrita do título)
  document.dispatchEvent(new CustomEvent('languagechange', { detail: currentLang }));
}

document.querySelectorAll('[data-lang]').forEach((btn) => {
  btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
});

// idioma inicial: o último escolhido; senão, o do browser (português → PT)
let saved = null;
try { saved = localStorage.getItem('mbv-lang'); } catch (e) {}
setLanguage(saved || ((navigator.language || '').toLowerCase().startsWith('pt') ? 'pt' : 'en'));
